// Area IM – run im-c1 (rok): the account history H1 after a list with pending rows (L0p): IM.3, IM.33, then a note and a
// rule changed, L2, and the undo of L2 and H1 from „Ostatnie importy”: IM.31.
import { join } from 'node:path'
import { expect, test, type Page } from '@playwright/test'
import { reading, start, useState } from './lab'
import { MBANK, Obs, PLIKI, catText, counters, expandAll, importAs, openFile, readFi, readable, short, statuses, step, txs } from './im-pomoc'

async function opRow(page: Page, query: string, period = true): Promise<void> {
  await page.keyboard.press('Control+2')
  await page.waitForTimeout(800)
  if (period) {
    await page.getByTestId('operations-period-menu').click()
    await page.getByTestId('operations-period-all').click()
  }
  await page.getByTestId('operations-search').fill(query)
  await page.waitForTimeout(800)
  await page.getByTestId('operation-row').first().click()
  await page.waitForTimeout(500)
}

test('im-c1: historia rachunku H1, telemetria, cofanie importów', async () => {

  const o = new Obs('im-c1')
  const { dataDir, ictjDir } = useState('rok', 'im-c1')
  const run = await start('im-c1', { dataDir, ictjDir })
  const { app, page, userData } = run
  const search = page.getByTestId('import-search')
  const balancesFile = async () => (await import('../e2e/files')).records(dataDir, 'balances')
  try {
    await expect(page.getByTestId('page-bridge')).toBeVisible({ timeout: 90_000 })
    const tx0 = await txs(dataDir)
    o.log('przed: salda (rekordy)', (await balancesFile()).map((b) => `${b.date} ${b.accountId === MBANK ? 'mBank' : b.accountId} ${b.kind ?? ''} ${b.amount ?? b.balance}`))

    // a list with the two pending rows of 02.11
    await step(o, page, 'L0p', async () => {
      o.log('L0p wynik', await importAs(app, page, userData, join(PLIKI, 'L0p.csv')))
    })

    // ---------------- IM.3 / IM.33 – H1
    await step(o, page, 'IM.3', async () => {
      await openFile(app, page, join(PLIKI, 'H1.csv'))
      await expandAll(page, true)
      o.log('IM.3 plik', await readable(page, '[data-testid="import-file"]'))
      o.log('IM.3 podgląd', await readable(page, '[data-testid="import-summary"]'))
      o.log('IM.3 liczniki', await counters(page))
      o.log('IM.3 dopasowania', await readable(page, '[data-testid="import-matches"]').catch(() => '(brak)'))
      o.log('IM.3 kategoryzacja', await catText(page))
      await o.shot(page, 'IM.3-H1')
      // a rule learned: JAN NOWAK's money → income, remembered
      await search.fill('nowak')
      await page.waitForTimeout(400)
      const g = page.locator('[data-testid="import-group"]').filter({ hasText: 'JAN NOWAK' }).first()
      await g.getByTestId('import-group-kind').selectOption({ label: 'Wpływ (przychód)' })
      await page.waitForTimeout(300)
      o.log('IM.31 grupa JAN NOWAK (reguła)', await readable(page, '[data-testid="import-groups"]'))
      // a second one: the café → kawa (remembered)
      await search.fill('mokka')
      await page.waitForTimeout(400)
      const m = page.locator('[data-testid="import-group"]').filter({ hasText: /MOKKA/ }).first()
      await m.getByTestId('import-group-category').selectOption({ label: 'Rozrywka i hobby · wyjścia' })
      await page.waitForTimeout(300)
      o.log('IM.31 grupa MOKKA (reguła)', await readable(page, '[data-testid="import-groups"]'))
      await search.fill('')
      reading('im', 'IM.33', 'rok + L0p, H1 podgląd', await counters(page))
      await page.getByTestId('import-run').click()
      await expect(page.getByTestId('import-done')).toBeVisible({ timeout: 60_000 })
      await page.waitForTimeout(1200)
      o.log('IM.33 toast', await statuses(page))
      o.log('IM.33 wynik', await readable(page, '[data-testid="import-done"]'))
      o.log('IM.33 telemetria', await readable(page, '[data-testid="bank-telemetry"]').catch(() => '(brak telemetrii)'))
      const tel = await readable(page, '[data-testid="bank-telemetry"]').catch(() => '')
      reading('im', 'IM.33', 'rok + L0p + H1 – telemetria', { tekst: tel.slice(0, 300) })
      await o.shot(page, 'IM.33-telemetria')
      o.log('IM.33 salda (rekordy)', (await balancesFile()).map((b) => JSON.stringify(b)))
      o.log('IM.33 import – ekran', (await readable(page, '[data-testid="page-import"]')).slice(0, 4000))
    })
    await step(o, page, 'IM.33-ekrany', async () => {
      await page.keyboard.press('Control+,')
      await page.getByTestId('settings-tab-accounts').click()
      await page.waitForTimeout(1500)
      o.log('IM.33 Ustawienia → Konta', await readable(page, 'main'))
      await o.shot(page, 'IM.33-konta')
      await page.keyboard.press('Control+Shift+M')
      await page.waitForTimeout(1500)
      o.log('IM.33 Meldunki', await readable(page, 'main'))
      await page.keyboard.press('Control+8')
      await page.waitForTimeout(2000)
      const cmd = await readable(page, 'main')
      o.log('IM.33 Dowództwo (fragment z „Inwentaryzacja”)', cmd.split('\n').filter((l, i, a) => /inwentaryz/i.test(l) || /inwentaryz/i.test(a[i - 1] ?? '') || /inwentaryz/i.test(a[i - 2] ?? '') || /inwentaryz/i.test(a[i + 1] ?? '')).join('\n') || cmd.slice(0, 3000))
      await page.keyboard.press('Control+1')
      await page.waitForTimeout(2000)
      o.log('IM.33 Mostek – odprawa', (await readable(page, '[data-testid="page-bridge"]')).slice(0, 3000))
    })
    // IM.3 – the café and the return in Operacje
    await step(o, page, 'IM.3-operacje', async () => {
      const all = await txs(dataDir)
      const news = all.filter((t) => !tx0.some((x) => x.id === t.id))
      o.log('IM.3 nowe operacje (H1 i L0p)', news.map(short))
      o.log('IM.3 zmienione operacje (połączone / rozliczone)', all.filter((t) => tx0.some((x) => x.id === t.id && JSON.stringify(x) !== JSON.stringify(t))).map(short))
      await opRow(page, 'mokka')
      o.log('IM.3 edytor kawiarni', (await readable(page, 'main')).split('Z banku').slice(1).join('Z banku').slice(0, 1500) || (await readable(page, 'main')).slice(-2500))
      await o.shot(page, 'IM.3-kawiarnia')
      await page.getByTestId('operations-search').fill('rossmann')
      await page.waitForTimeout(700)
      o.log('IM.3 Rossmann na liście', await page.getByTestId('operation-row').allInnerTexts())
      await page.getByTestId('operations-search').fill('nowak')
      await page.waitForTimeout(700)
      await page.getByTestId('operation-row').first().click()
      await page.waitForTimeout(500)
      o.log('IM.3 edytor przelewu JAN NOWAK', (await readable(page, 'main')).slice(-2500))
    })

    // ---------------- IM.31 – a note on the merged entry, a learned rule changed, L2, undo
    await step(o, page, 'IM.31', async () => {
      await opRow(page, 'bar pod lip')
      const note = page.getByTestId('operation-note')
      await note.fill('notatka po imporcie H1')
      await note.press('Control+Enter')
      await page.waitForTimeout(800)
      await page.getByTestId('operations-search').fill('')
      o.log('IM.31 Bar pod Lipą po notatce', (await txs(dataDir)).filter((t) => /bar pod lip/i.test(String(t.counterparty))).map(short).slice(-3))
      await page.keyboard.press('Control+,')
      await page.getByTestId('settings-tab-import').click()
      await page.waitForTimeout(1500)
      const rule = page.locator('[data-testid="import-rule"]').filter({ hasText: /mokka/i }).first()
      o.log('IM.31 reguła MOKKA przed zmianą', await rule.innerText().catch(() => '(brak)'))
      await rule.getByTestId('import-rule-edit').click()
      await page.waitForTimeout(400)
      await page.getByTestId('import-rule-editor').getByTestId('import-rule-edit-category').selectOption({ label: 'Jedzenie · kawa i przekąski' })
      await page.getByTestId('import-rule-save').click()
      await page.waitForTimeout(800)
      o.log('IM.31 zmiana reguły – toast', await statuses(page))
      o.log('IM.31 reguły (fi.json)', readFi(dataDir).settings.import.rules.map((r: Record<string, unknown>) => `${r.match} ${r.direction} ${r.kind} ${String(r.categoryId).slice(-3)} learned=${r.learned}`))
      o.log('IM.31 L2 wynik', await importAs(app, page, userData, join(PLIKI, 'L2.csv')))
      await page.keyboard.press('Control+,')
      await page.getByTestId('settings-tab-import').click()
      await page.waitForTimeout(1500)
      o.log('IM.31 Ostatnie importy', await readable(page, '[data-testid="recent-imports"]'))
      const rows = page.getByTestId('recent-import')
      o.log('IM.31 przycisk przy H1 (starszym)', await rows.filter({ hasText: 'H1.csv' }).innerText().catch(() => '-'))
      o.log('IM.31 dymek „—”', await rows.filter({ hasText: 'H1.csv' }).locator('[title]').last().getAttribute('title').catch(() => '-'))
      await o.shot(page, 'IM.31-ostatnie-importy')
      // undo L2
      await rows.filter({ hasText: 'L2.csv' }).getByTestId('recent-import-undo').click()
      await page.waitForTimeout(600)
      o.log('IM.31 okno cofnięcia L2', await readable(page, '[data-testid="import-undo-dialog"]').catch(async () => (await page.getByRole('dialog').allInnerTexts()).join('\n')))
      await page.getByTestId('import-undo-confirm').click()
      await page.waitForTimeout(2500)
      o.log('IM.31 cofnięcie L2 – toast', await statuses(page))
      o.log('IM.31 Ostatnie importy po cofnięciu L2', await readable(page, '[data-testid="recent-imports"]'))
      // undo H1
      await rows.filter({ hasText: 'H1.csv' }).getByTestId('recent-import-undo').click()
      await page.waitForTimeout(600)
      o.log('IM.31 okno cofnięcia H1', await readable(page, '[data-testid="import-undo-dialog"]').catch(async () => (await page.getByRole('dialog').allInnerTexts()).join('\n')))
      await o.shot(page, 'IM.31-okno-H1')
      await page.getByTestId('import-undo-confirm').click()
      await page.waitForTimeout(2500)
      o.log('IM.31 cofnięcie H1 – toast', await statuses(page))
      o.log('IM.31 Ostatnie importy po cofnięciu H1', await readable(page, '[data-testid="recent-imports"]'))
      await o.shot(page, 'IM.31-po-cofnieciu')
      const all = await txs(dataDir)
      o.log('IM.31 Bar pod Lipą po cofnięciu H1', all.filter((t) => /bar pod lip/i.test(String(t.counterparty)) && (t.date as string) >= '2026-10-27').map(short))
      o.log('IM.31 Apteka po cofnięciu H1', all.filter((t) => /apteka/i.test(String(t.counterparty)) && (t.date as string) >= '2026-10-27').map(short))
      o.log('IM.31 nierozliczone po cofnięciu H1', all.filter((t) => (t.bank as Record<string, unknown> | null)?.pending).map(short))
      o.log('IM.31 operacje 27.10+ (mBank) po cofnięciu', all.filter((t) => t.accountId === MBANK && (t.date as string) >= '2026-10-27').map(short))
      o.log('IM.31 reguły po cofnięciu', readFi(dataDir).settings.import.rules.map((r: Record<string, unknown>) => `${r.match} ${r.direction} ${r.kind} ${String(r.categoryId).slice(-3)} learned=${r.learned}`))
      o.log('IM.31 salda (rekordy) po cofnięciu', (await balancesFile()).map((b) => `${b.date} ${b.accountId === MBANK ? 'mBank' : b.accountId} ${JSON.stringify(b).slice(0, 200)}`))
      await page.getByTestId('settings-tab-accounts').click()
      await page.waitForTimeout(1200)
      o.log('IM.31 Ustawienia → Konta po cofnięciu', await readable(page, 'main'))
    })
    o.log('błędy okna', run.errors)
  } finally {
    await app.close()
  }
})
