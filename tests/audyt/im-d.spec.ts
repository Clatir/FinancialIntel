// Area IM – runs im-d1 / im-d2: accounts of the import. im-d1 (rok prepared): a transfer mBank → mBank oszczędności from
// L1, then K2 on the savings account (IM.22), files of another account number (IM.38). im-d2 (rok): L1 on Portfel XTB
// first, then on mBank (IM.39).
import { join } from 'node:path'
import { expect, test, type Page } from '@playwright/test'
import { reading, start, useState } from './lab'
import { MBANK, Obs, PLIKI, SAVINGS, WALLET, counters, expandAll, importAs, openFile, prepareImportState, readFi, readable, short, statuses, step, txs } from './im-pomoc'

async function accountsText(page: Page): Promise<string> {
  await page.keyboard.press('Control+3')
  await page.waitForTimeout(600)
  return readable(page, '[data-testid="balance-check"]').catch(async () => (await readable(page, '[data-testid="page-import"]')).slice(0, 600))
}

test('im-d1: druga strona przelewu z pliku drugiego konta, plik z innego rachunku', async () => {
  const o = new Obs('im-d1')
  const { dataDir, ictjDir } = useState('rok', 'im-d1')
  o.log('stan', prepareImportState(dataDir))
  const run = await start('im-d1', { dataDir, ictjDir })
  const { app, page, userData } = run
  const search = page.getByTestId('import-search')
  try {
    await expect(page.getByTestId('page-bridge')).toBeVisible({ timeout: 90_000 })
    // L1 with the transfer of 1000 zł → mBank oszczędności (one operation)
    await step(o, page, 'L1', async () => {
      await openFile(app, page, join(PLIKI, 'L1.csv'))
      await search.fill('jan kapitan')
      await page.waitForTimeout(500)
      await expandAll(page, true)
      const rows = page.locator('[data-testid="import-group"][data-label="JAN KAPITAN"]').getByTestId('import-row')
      for (let i = 0; i < (await rows.count()); i++) {
        const r = rows.nth(i)
        if (/NA OSZCZ/.test(await r.innerText())) await r.getByTestId('import-row-counter-account').selectOption({ label: '→ mBank oszczędności' })
      }
      await search.fill('')
      await page.getByTestId('import-run').click()
      await expect(page.getByTestId('import-done')).toBeVisible({ timeout: 60_000 })
      o.log('L1 wynik', await readable(page, '[data-testid="import-done"]'))
      o.log('przelew po L1', (await txs(dataDir)).filter((t) => t.kind === 'transfer' && t.counterAccountId === SAVINGS).map((t) => JSON.stringify(t)))
      o.log('salda po L1', await accountsText(page))
    })
    // ---------------- IM.22
    await step(o, page, 'IM.22', async () => {
      await page.getByTestId('import-close').click({ timeout: 1500 }).catch(() => undefined)
      await openFile(app, page, join(PLIKI, 'K2.csv'))
      await page.getByTestId('import-account').selectOption({ label: 'mBank oszczędności' })
      await page.waitForTimeout(1500)
      o.log('IM.22 plik', await readable(page, '[data-testid="import-file"]'))
      o.log('IM.22 podgląd', await readable(page, '[data-testid="import-summary"]'))
      o.log('IM.22 dopasowania', await readable(page, '[data-testid="import-matches"]').catch(() => '(brak)'))
      o.log('IM.22 liczniki', await counters(page))
      await o.shot(page, 'IM.22-podglad')
      // unticked: what it would be
      const side = page.getByTestId('import-side').first()
      if (await side.count()) {
        await side.getByTestId('import-side-join').uncheck()
        await page.waitForTimeout(500)
        o.log('IM.22 strona odznaczona', await side.innerText())
        o.log('IM.22 liczniki (odznaczona)', await counters(page))
        await o.shot(page, 'IM.22-odznaczona')
        await side.getByTestId('import-side-join').check()
        await page.waitForTimeout(500)
      }
      await page.getByTestId('import-run').click()
      await expect(page.getByTestId('import-done')).toBeVisible({ timeout: 60_000 })
      await page.waitForTimeout(800)
      o.log('IM.22 wynik', await readable(page, '[data-testid="import-done"]'))
      o.log('IM.22 toast', await statuses(page))
      const tr = (await txs(dataDir)).filter((t) => (t.kind === 'transfer' && (t.counterAccountId === SAVINGS || t.accountId === SAVINGS)) || (t.accountId === SAVINGS))
      o.log('IM.22 operacje konta oszczędności / przelewy', tr.map((t) => JSON.stringify(t)))
      o.log('IM.22 salda', await accountsText(page))
      await page.keyboard.press('Control+2')
      await page.waitForTimeout(800)
      await page.getByTestId('operations-period-menu').click()
      await page.getByTestId('operations-period-all').click()
      await page.getByTestId('operations-search').fill('oszcz')
      await page.waitForTimeout(800)
      o.log('IM.22 Operacje – lista', await page.getByTestId('operation-row').allInnerTexts())
      await page.getByTestId('operation-row').first().click()
      await page.waitForTimeout(500)
      o.log('IM.22 edytor przelewu', (await readable(page, 'main')).split('Notatka').slice(-1)[0]!.slice(0, 1500))
      await o.shot(page, 'IM.22-przelew')
      await page.getByTestId('operations-search').fill('')
      await page.keyboard.press('Control+7')
      await page.waitForTimeout(2000)
      const radar = await readable(page, 'main')
      o.log('IM.22 Radar – salda kont', radar.split('\n').filter((l, i, a) => /oszcz/i.test(l) || /oszcz/i.test(a[i - 1] ?? '') || /oszcz/i.test(a[i - 2] ?? '')).join('\n'))
      reading('im', 'IM.22', 'rok przygotowany + L1 + K2 – przelew mBank → oszczędności', { przelew: tr.map((t) => `${t.date} ${t.amount} ${t.counterDate ?? ''}`).join('; ') })
    })
    // ---------------- IM.38
    await step(o, page, 'IM.38', async () => {
      await page.keyboard.press('Control+3')
      await page.getByTestId('import-close').click({ timeout: 1500 }).catch(() => undefined)
      await openFile(app, page, join(PLIKI, 'R.csv'))
      o.log('IM.38 R na mBank – ostrzeżenie', await page.getByTestId('import-account-warning').innerText().catch(() => '(brak ostrzeżenia)'))
      await o.shot(page, 'IM.38-R')
      await page.getByTestId('import-close').click()
      await openFile(app, page, join(PLIKI, 'K5555.csv'))
      o.log('IM.38 …5555 na mBank – ostrzeżenie', await page.getByTestId('import-account-warning').innerText().catch(() => '(brak ostrzeżenia)'))
      await o.shot(page, 'IM.38-5555')
      await page.getByTestId('import-account').selectOption({ label: 'mBank oszczędności' })
      await page.waitForTimeout(1000)
      o.log('IM.38 …5555 na mBank oszczędności – ostrzeżenie', await page.getByTestId('import-account-warning').innerText().catch(() => '(brak ostrzeżenia)'))
      await page.getByTestId('import-close').click()
      await openFile(app, page, join(PLIKI, 'R.csv'))
      const before = readFi(dataDir).settings.import.accountNumbers
      await page.getByTestId('import-run').click()
      await expect(page.getByTestId('import-done')).toBeVisible({ timeout: 60_000 })
      o.log('IM.38 R zaimportowany', await readable(page, '[data-testid="import-done"]'))
      o.log('IM.38 numery rachunków przed / po', { before, after: readFi(dataDir).settings.import.accountNumbers })
      await page.getByTestId('import-close').click({ timeout: 1500 }).catch(() => undefined)
      await openFile(app, page, join(PLIKI, 'L1.csv'))
      o.log('IM.38 L1 (…0001) na mBank po imporcie R – ostrzeżenie', await page.getByTestId('import-account-warning').innerText().catch(() => '(brak ostrzeżenia)'))
    })
    o.log('błędy okna', run.errors)
  } finally {
    await app.close()
  }
})

test('im-d2: plik zaimportowany najpierw na złe konto', async () => {
  const o = new Obs('im-d2')
  const { dataDir, ictjDir } = useState('rok', 'im-d2')
  const run = await start('im-d2', { dataDir, ictjDir })
  const { app, page } = run
  try {
    await expect(page.getByTestId('page-bridge')).toBeVisible({ timeout: 90_000 })
    const s0 = await accountsText(page)
    o.log('salda przed', s0)
    await step(o, page, 'IM.39-portfel', async () => {
      await openFile(app, page, join(PLIKI, 'L1.csv'))
      await page.getByTestId('import-account').selectOption({ label: 'Portfel XTB' })
      await page.waitForTimeout(1500)
      o.log('IM.39 L1 na Portfel – ostrzeżenie', await page.getByTestId('import-account-warning').innerText().catch(() => '(brak ostrzeżenia)'))
      o.log('IM.39 L1 na Portfel – podgląd', await readable(page, '[data-testid="import-summary"]'))
      o.log('IM.39 L1 na Portfel – dopasowania', await readable(page, '[data-testid="import-matches"]').catch(() => '(brak)'))
      await o.shot(page, 'IM.39-portfel')
      // a note on one of them after the import
      await page.getByTestId('import-run').click()
      await expect(page.getByTestId('import-done')).toBeVisible({ timeout: 60_000 })
      o.log('IM.39 wynik na Portfel', await readable(page, '[data-testid="import-done"]'))
      o.log('IM.39 salda po imporcie na Portfel', await accountsText(page))
      await page.keyboard.press('Control+2')
      await page.waitForTimeout(800)
      await page.getByTestId('operations-period-menu').click()
      await page.getByTestId('operations-period-all').click()
      await page.getByTestId('operations-search').fill('ślusarz')
      await page.waitForTimeout(700)
      await page.getByTestId('operation-row').first().click()
      await page.getByTestId('operation-category').selectOption({ label: 'Dom · wyposażenie' })
      const note = page.getByTestId('operation-note')
      await note.fill('notatka na złym koncie')
      await note.press('Control+Enter')
      await page.waitForTimeout(800)
      await page.getByTestId('operations-search').fill('')
    })
    await step(o, page, 'IM.39-mbank', async () => {
      const tx1 = await txs(dataDir)
      await page.keyboard.press('Control+3')
      await page.getByTestId('import-close').click({ timeout: 1500 }).catch(() => undefined)
      await openFile(app, page, join(PLIKI, 'L1.csv'))
      o.log('IM.39 konto wybrane po otwarciu (zostaje z poprzedniego pliku?)', await page.getByTestId('import-account').evaluate((s: HTMLSelectElement) => s.options[s.selectedIndex]?.text))
      await page.getByTestId('import-account').selectOption({ label: 'mBank' })
      await page.waitForTimeout(1500)
      o.log('IM.39 L1 na mBank – ostrzeżenie', await page.getByTestId('import-account-warning').innerText().catch(() => '(brak ostrzeżenia)'))
      o.log('IM.39 L1 na mBank – podgląd', await readable(page, '[data-testid="import-summary"]'))
      o.log('IM.39 L1 na mBank – liczniki', await counters(page))
      const ew = page.getByTestId('import-elsewhere')
      o.log('IM.39 sekcja „Już w budżecie na innym koncie”', await readable(page, '[data-testid="import-matches"]').catch(() => '(brak)'))
      const n = await ew.count()
      if (n) {
        await ew.first().getByTestId('import-elsewhere-move').uncheck()
        await page.waitForTimeout(500)
        o.log('IM.39 po odznaczeniu jednej – liczniki', await counters(page))
        o.log('IM.39 odznaczona', await ew.first().innerText())
      }
      await o.shot(page, 'IM.39-mbank')
      await page.getByTestId('import-run').click()
      await expect(page.getByTestId('import-done')).toBeVisible({ timeout: 60_000 })
      o.log('IM.39 wynik na mBank', await readable(page, '[data-testid="import-done"]'))
      o.log('IM.39 salda po', await accountsText(page))
      const tx2 = await txs(dataDir)
      o.log('IM.39 operacji przed / po', [tx1.length, tx2.length])
      o.log('IM.39 ŚLUSARZ po', tx2.filter((t) => /ŚLUSARZ/i.test(String(t.counterparty))).map(short))
      o.log('IM.39 operacje 27.10+ na Portfelu po', tx2.filter((t) => t.accountId === WALLET && (t.date as string) >= '2026-10-19' && t.bank).map(short))
      o.log('IM.39 duplikaty mBank (ten sam wiersz)', tx2.filter((t) => t.accountId === MBANK && (t.date as string) >= '2026-10-27' && t.bank).length)
      const dupl = new Map<string, number>()
      for (const t of tx2.filter((x) => x.accountId === MBANK && x.bank && (x.date as string) >= '2026-10-19' && (x.date as string) <= '2026-10-26')) dupl.set(`${t.date}|${t.amount}`, (dupl.get(`${t.date}|${t.amount}`) ?? 0) + 1)
      o.log('IM.39 mBank 19–26.10: wiersze podwójne (data|kwota)', [...dupl.entries()].filter(([, n]) => n > 1).map(([k]) => k))
      await page.keyboard.press('Control+Shift+M')
      await page.waitForTimeout(1500)
      o.log('IM.39 Meldunki – duplikaty', (await readable(page, 'main')).split(String.fromCharCode(10)).filter((l) => /duplikat/i.test(l)))
      reading('im', 'IM.39', 'rok + L1 na Portfel, potem L1 na mBank', { salda: (await accountsText(page)).replace(/\n/g, ' ') })
    })
    o.log('błędy okna', run.errors)
  } finally {
    await app.close()
  }
})
