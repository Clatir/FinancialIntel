test('IN.11 zamknięcia okien odłączonych', async () => {
  const N = 'in-odlaczone2'
  const r = await run(N)
  const { app, page } = r
  try {
    await mute(app)
    await page.keyboard.press('Control+1')
    await page.getByTestId('page-bridge').waitFor()
    await page.getByTestId('panel-detach').first().click()
    await page.waitForTimeout(2000)
    await page.getByTestId('panel-detach').first().click()
    await page.waitForTimeout(2000)
    const wins = () => app.windows().filter((w) => w.url().includes('detach'))
    say('IN.11 okna odłączone', wins().length)
    await wins()[0]!.getByTestId('detached-attach').click()
    await page.waitForTimeout(1500)
    say('IN.11 po „Przywróć do aplikacji” w odłączonym', { okna: wins().length, notatki: await page.getByTestId('panel-detached-note').count(), paneli: await page.getByTestId('panel-collapse').count() })
    // click an item in the detached window: leads the main window
    await page.keyboard.press('Control+2')
    await page.waitForTimeout(700)
    const d = wins()[0]!
    const link = d.locator('button, a').filter({ hasText: /Asteroida|mBank|Odsłuchaj|przydział/ }).first()
    if (await link.count()) {
      await link.click()
      await page.waitForTimeout(1200)
      say('IN.11 klik w odłączonym – główne okno', { ekran: await page.evaluate(() => document.querySelector('[data-testid^="page-"]')?.getAttribute('data-testid')), okno: (await text(page, 'main')).slice(0, 80) })
    }
    // closing the main window closes the detached ones (closeToTray off for this)
    await goSettings(page, 'system')
    await page.getByTestId('tray-close').click()
    await page.waitForTimeout(600)
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((w) => !w.getURL().includes('detached') && !w.getURL().includes('quick'))!.close())
    await page.waitForTimeout(3000)
    say('IN.11 po zamknięciu głównego – proces', { exit: app.process().exitCode })
  } finally {
    await app.close().catch(() => undefined)
  }
})

test('IN.14 potwierdzenia, IN.15 pola', async () => {
  const N = 'in-modalne2'
  const r = await run(N)
  const { app, page } = r
  try {
    await page.keyboard.press('Control+2')
    await page.waitForTimeout(1200)
    say('IN.14 wierszy w bieżącym miesiącu', await page.getByTestId('operation-row').count())
    await page.getByTestId('operation-row').first().click()
    await page.waitForTimeout(600)
    const del = page.getByTestId('operation-delete')
    say('IN.14 przycisk', await del.innerText())
    await del.click()
    await page.waitForTimeout(400)
    say('IN.14 po 1. kliknięciu', await del.innerText().catch(() => '(brak)'))
    await snap(page, 'IN.14-usun')
    await page.keyboard.press('Escape')
    await page.waitForTimeout(500)
    say('IN.14 po Esc', { przycisk: await del.innerText().catch(() => '(brak)'), wierszy: await page.getByTestId('operation-row').count(), edytor: await page.getByTestId('operation-editor').count() })
    await del.click().catch(() => undefined)
    await page.waitForTimeout(300)
    await page.mouse.click(700, 8)
    await page.waitForTimeout(600)
    say('IN.14 po kliknięciu obok', { przycisk: await del.innerText().catch(() => '(brak)'), wierszy: await page.getByTestId('operation-row').count() })
    await del.click().catch(() => undefined)
    await page.waitForTimeout(300)
    await page.keyboard.press('Enter')
    await page.waitForTimeout(800)
    say('IN.14 Enter po 1. kliknięciu (fokus na przycisku?)', { fokus: await page.evaluate(() => document.activeElement?.getAttribute('data-testid') ?? document.activeElement?.tagName), wierszy: await page.getByTestId('operation-row').count(), toasts: await toasts(page) })
    // Zmień scenariusz (Esc / klik obok)
    await goSettings(page, 'ictj')
    const sel = page.getByTestId('ictj-forecast')
    const opts = await sel.locator('option').evaluateAll((os) => os.map((o) => (o as HTMLOptionElement).value))
    const cur = await sel.inputValue()
    await sel.selectOption(opts.find((v) => v && v !== cur)!)
    await page.waitForTimeout(500)
    await page.keyboard.press('Escape')
    await page.waitForTimeout(400)
    say('IN.14 „Zmień scenariusz” po Esc', { pytanie: await page.getByTestId('ictj-forecast-confirm').count(), ekran: await page.getByTestId('settings-tab-ictj').count(), fi: fiOf(N).settings.ictj.forecastId === cur })
    await page.mouse.click(700, 8)
    await page.waitForTimeout(300)
    say('IN.14 „Zmień scenariusz” po kliknięciu obok', { pytanie: await page.getByTestId('ictj-forecast-confirm').count() })
    // Historia
    await goSettings(page, 'accounts')
    await page.getByRole('button', { name: /historia/i }).first().click()
    await page.waitForTimeout(500)
    say('IN.14 Historia – fokus po otwarciu', await page.evaluate(() => document.activeElement?.tagName + ':' + (document.activeElement?.textContent ?? '').slice(0, 20)))
    await page.keyboard.press('Escape')
    await page.waitForTimeout(400)
    say('IN.14 Historia – po Esc fokus', await page.evaluate(() => document.activeElement?.tagName + ':' + (document.activeElement?.textContent ?? '').slice(0, 20)))
    // IN.15 fields
    await page.keyboard.press('Control+2')
    await page.waitForTimeout(1000)
    await page.getByTestId('operations-prev-month').click()
    await page.waitForTimeout(800)
    await page.getByTestId('operation-row').first().click()
    await page.waitForTimeout(600)
    const probe = async (label: string, tid: string, val: string) => {
      const f = page.getByTestId(tid)
      const old = await f.inputValue()
      await f.click()
      await f.press('Control+a')
      await f.pressSequentially(val)
      await f.press('Escape')
      await page.waitForTimeout(500)
      const afterEsc = await f.inputValue()
      await f.click()
      await f.press('Control+a')
      await f.pressSequentially(val)
      await f.press('Enter')
      await page.waitForTimeout(800)
      const afterEnter = await f.inputValue()
      say(`IN.15 ${label}`, { przed: old, poEsc: afterEsc, poEnter: afterEnter, edytor: await page.getByTestId('operation-editor').count() })
    }
    await probe('kwota', 'operation-amount', '7,77')
    await probe('data', 'operation-date', '01.10.2026')
    await probe('godzina', 'operation-time', '10:11')
    await probe('kontrahent', 'operation-counterparty', 'EscEnter-Test')
    await probe('notatka', 'operation-note', 'notatka-test')
    await page.keyboard.press('Control+4')
    await page.waitForTimeout(1000)
    const fields = page.locator('[data-testid="page-month"] input')
    say('IN.15 Plan – pola', await fields.evaluateAll((els) => els.slice(0, 10).map((e) => `${e.getAttribute('data-testid') ?? e.getAttribute('aria-label')}=${(e as HTMLInputElement).value}`)))
    for (let i = 0; i < 3; i++) {
      const f = fields.nth(i)
      if (!(await f.count()) || (await f.isDisabled())) continue
      const old = await f.inputValue()
      await f.click()
      await f.press('Control+a')
      await f.pressSequentially('1')
      await f.press('Escape')
      await page.waitForTimeout(400)
      const e1 = await f.inputValue()
      await f.click()
      await f.press('Control+a')
      await f.pressSequentially('1')
      await f.press('Enter')
      await page.waitForTimeout(600)
      say(`IN.15 Plan pole ${i}`, { przed: old, poEsc: e1, poEnter: await f.inputValue() })
    }
    await page.keyboard.press('Control+5')
    await page.waitForTimeout(1000)
    say('IN.15 Ładownia – pola', await page.locator('[data-testid="page-cargo"] input').evaluateAll((els) => els.slice(0, 8).map((e) => `${e.getAttribute('data-testid') ?? e.getAttribute('aria-label')}=${(e as HTMLInputElement).value}`)))
    await page.keyboard.press('Control+6')
    await page.waitForTimeout(1000)
    say('IN.15 Mapa – pola', await page.locator('[data-testid="page-starmap"] input').evaluateAll((els) => els.slice(0, 8).map((e) => `${e.getAttribute('data-testid') ?? e.getAttribute('aria-label')}=${(e as HTMLInputElement).value}`)))
  } finally {
    await app.close()
  }
})
