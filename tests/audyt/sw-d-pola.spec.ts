/**
 * SW.15, SW.17, SW.18, SW.19, SW.22, SW.23, SW.24, SW.31, SW.32 – the receipt's split, the captain's log from the
 * threshold, the quiet hours by the hour typed, the date / time / amount fields, a negative amount, Esc / × / Enter,
 * one save on a double Enter or click. State: rok.
 */
import { test, type Page } from '@playwright/test'
import { reading, text } from './lab'
import { CAT, added, bridge, brief, category, enterSave, kind, log, openFresh, openQuick, openRok, ops, qread, quickVisible, snap, typeAmount, typeIn, waitHidden } from './sw-pomoc'

const body = (q: Page) => q.locator('body').innerText().then((x) => x.replace(/\s+/g, ' '))
const linesText = (q: Page) => q.getByTestId('quick-lines').innerText().then((x) => x.replace(/\s+/g, ' ').replace(/— bez kategorii —.*?Gotówka/g, '[lista kategorii]'))
const lineVals = (q: Page) =>
  q.evaluate(() =>
    [...document.querySelectorAll('[data-testid="quick-lines"] > div.grid')].map((row) => {
      const a = row.querySelector('input') as HTMLInputElement | null
      const s = row.querySelectorAll('select')
      return `${a?.value ?? ''} ${(s[0] as HTMLSelectElement | undefined)?.selectedOptions[0]?.textContent ?? ''} ${(s[1] as HTMLSelectElement | undefined)?.selectedOptions[0]?.textContent ?? ''}`
    })
  )

test('SW pola: 15, 17, 18, 19, 22, 23, 24, 31, 32', async () => {
  test.setTimeout(25 * 60_000)
  const run = 'sw-d'
  const { app, page, dataDir } = await openRok(run)
  try {
    // ---- SW.15 – podział paragonu 187,45 Biedronka
    let before = await ops(dataDir)
    const b0 = await bridge(page)
    let q = await openFresh(app, page)
    await typeAmount(q, '187,45')
    await typeIn(q, 'quick-counterparty', 'Biedronka')
    await category(q, CAT.food)
    log(run, 'SW.15 dymek +', await q.getByTestId('quick-split').getAttribute('title'))
    await q.getByTestId('quick-split').click()
    await q.waitForTimeout(200)
    log(run, 'SW.15 po podziale', await lineVals(q), await linesText(q))
    const parts = q.locator('[data-testid="quick-lines"] input[aria-label^="Część"]')
    const pcats = q.locator('[data-testid="quick-lines"] select[aria-label="Kategoria"]')
    await parts.nth(0).click()
    await parts.nth(0).fill('150,00')
    await parts.nth(0).press('Tab')
    log(run, 'SW.15 część 1 = 150', await lineVals(q), await linesText(q))
    await q.getByText('+ część').click()
    await q.waitForTimeout(200)
    log(run, 'SW.15 + część', await lineVals(q), await linesText(q))
    await snap(q, 'SW.15-plus-czesc')
    await q.getByText('bez podziału').click()
    await q.waitForTimeout(200)
    log(run, 'SW.15 bez podziału', await qread(q), 'części', await q.getByTestId('quick-lines').count())
    await q.getByTestId('quick-split').click()
    await parts.nth(0).click()
    await parts.nth(0).fill('150,00')
    await parts.nth(0).press('Tab')
    await parts.nth(1).click()
    await parts.nth(1).fill('30,00')
    await parts.nth(1).press('Tab')
    await pcats.nth(1).selectOption(CAT.chem)
    log(run, 'SW.15 suma 180', await lineVals(q), await linesText(q), '| podgląd', (await qread(q)).preview)
    log(run, 'SW.15 Enter przy 180', await enterSave(app, q, 'quick-counterparty'))
    await snap(q, 'SW.15-niezgodna-suma')
    log(run, 'SW.15 pliki po odmowie', (await added(dataDir, before)).length)
    await parts.nth(1).click()
    await parts.nth(1).fill('37,45')
    await parts.nth(1).press('Tab')
    const p15 = await qread(q)
    log(run, 'SW.15 poprawione', await lineVals(q), '| podgląd', p15.preview)
    await snap(q, 'SW.15-podglad')
    log(run, 'SW.15 Enter', await enterSave(app, q, 'quick-counterparty'))
    await page.waitForTimeout(1200)
    const b1 = await bridge(page)
    log(run, 'SW.15 mostek przed/po', b0.energy, b1.energy, '| koperty po', b1.envelopes.slice(0, 200))
    log(run, 'SW.15 nowe', (await added(dataDir, before)).map(brief))
    await page.keyboard.press('Control+2')
    await page.waitForTimeout(2000)
    log(run, 'SW.15 Operacje', (await page.getByTestId('operation-row').allInnerTexts()).slice(0, 3).map((x) => x.replace(/\s+/g, ' ')))
    await snap(page, 'SW.15-operacje')
    await page.keyboard.press('Control+1')
    reading('sw', 'SW.15', 'rok', { energiaPrzed: b0.energy, energiaPo: b1.energy, podglad: p15.preview, kopertyPrzed: b0.envelopes.slice(0, 200), kopertyPo: b1.envelopes.slice(0, 200) })

    // ---- SW.17 – podział, potem „Wpływ”
    before = await ops(dataDir)
    q = await openFresh(app, page)
    await typeAmount(q, '60,00')
    await q.getByTestId('quick-split').click()
    await parts.nth(0).click()
    await parts.nth(0).fill('30,00')
    await parts.nth(0).press('Tab')
    await parts.nth(1).click()
    await parts.nth(1).fill('30,00')
    await parts.nth(1).press('Tab')
    log(run, 'SW.17 części', await lineVals(q))
    await kind(q, 'Wpływ')
    log(run, 'SW.17 po Wpływ – części widoczne', await q.getByTestId('quick-lines').count(), (await qread(q)).preview)
    log(run, 'SW.17 Enter', await enterSave(app, q))
    await page.waitForTimeout(800)
    log(run, 'SW.17 nowe', (await added(dataDir, before)).map(brief))

    // ---- SW.18 – plan czy impuls (próg 200,00)
    before = await ops(dataDir)
    q = await openFresh(app, page)
    await typeAmount(q, '199,99')
    log(run, 'SW.18 199,99 dziennik', await q.getByTestId('quick-log').count())
    await typeAmount(q, '200,00')
    log(run, 'SW.18 200,00 dziennik', (await q.getByTestId('quick-log').count()) ? await q.getByTestId('quick-log').innerText() : '(brak)', '| placeholder', await q.getByTestId('quick-log-note').getAttribute('placeholder').catch(() => null))
    await q.locator('[aria-label="Plan czy impuls"]').getByRole('radio', { name: 'impuls' }).click()
    await typeIn(q, 'quick-log-note', 'wyprzedaż')
    await category(q, CAT.clothes)
    await typeIn(q, 'quick-counterparty', 'Zalando')
    await snap(q, 'SW.18')
    log(run, 'SW.18 Enter', await enterSave(app, q, 'quick-counterparty'))
    await page.waitForTimeout(800)
    log(run, 'SW.18 nowe', (await added(dataDir, before)).map(brief))
    q = await openFresh(app, page)
    await kind(q, 'Wpływ')
    await typeAmount(q, '500,00')
    log(run, 'SW.18 wpływ 500 dziennik', await q.getByTestId('quick-log').count())
    await q.keyboard.press('Escape')
    await waitHidden(app)
    await page.keyboard.press('Control+2')
    await page.waitForTimeout(2000)
    const zr = page.getByTestId('operation-row').filter({ hasText: 'Zalando' }).first()
    log(run, 'SW.18 Operacje wiersz', (await zr.innerText().catch(() => '(brak)')).replace(/\s+/g, ' '))
    await zr.click().catch(() => undefined)
    await page.waitForTimeout(800)
    const ed = page.getByTestId('operation-editor')
    log(run, 'SW.18 Operacje edytor – „wyprzedaż”', await ed.evaluate((e) => [...e.querySelectorAll('input,textarea')].map((i) => (i as HTMLInputElement).value).filter((v) => v.includes('wyprzed'))).catch(() => '(brak edytora)'), '| plan/impuls', await page.locator('[aria-label="Plan czy impuls"] [aria-checked="true"]').innerText().catch(() => '(brak)'))
    await snap(page, 'SW.18-operacje')
    await page.keyboard.press('Escape')
    await page.keyboard.press('Control+9')
    await page.waitForTimeout(2500)
    log(run, 'SW.18 Wywiad dziennik', (await page.getByTestId('intel-log').innerText().catch(() => '(brak intel-log)')).replace(/\s+/g, ' ').slice(0, 900))
    const wy = await text(page, 'main')
    log(run, 'SW.18 Wywiad – „wyprzedaż” w tekście', wy.includes('wyprzedaż'))
    await page.getByTestId('intel-log').scrollIntoViewIfNeeded().catch(() => undefined)
    await snap(page, 'SW.18-wywiad')
    await page.keyboard.press('Control+1')

    // ---- SW.19 – cisza nocna po godzinie zakupu
    before = await ops(dataDir)
    q = await openFresh(app, page)
    await typeAmount(q, '35,00')
    await category(q, CAT.food)
    for (const h of ['22:59', '23:00', '23:30', '00:15', '04:59', '05:00']) {
      await typeIn(q, 'quick-time', h)
      const t = await body(q)
      log(run, `SW.19 ${h}`, (await qread(q)).time, '| znaczek', /cisza nocna(?! \()/.test(t.replace('Potwierdzam zakup w ciszy nocnej', '')), '| dziennik', (await q.getByTestId('quick-log').count()) ? (await q.getByTestId('quick-log').innerText()).replace(/\s+/g, ' ') + ' | placeholder: ' + (await q.getByTestId('quick-log-note').getAttribute('placeholder')) : '(brak)')
      if (h === '23:30') await snap(q, 'SW.19-2330')
    }
    await typeIn(q, 'quick-time', '00:15')
    log(run, 'SW.19 00:15 Enter bez niczego', await enterSave(app, q, 'quick-time'))
    await q.getByTestId('quick-night-ok').check()
    log(run, 'SW.19 00:15 tylko potwierdzenie', await enterSave(app, q, 'quick-time'))
    await snap(q, 'SW.19-odmowa')
    await typeIn(q, 'quick-log-note', 'pizza po dyżurze')
    log(run, 'SW.19 00:15 potwierdzenie + notka', await enterSave(app, q, 'quick-log-note'))
    await page.waitForTimeout(800)
    q = await openFresh(app, page)
    await kind(q, 'Wpływ')
    await typeAmount(q, '35,00')
    await typeIn(q, 'quick-time', '23:30')
    log(run, 'SW.19 wpływ 23:30 dziennik', await q.getByTestId('quick-log').count(), '| tekst', (await body(q)).includes('cisza nocna'))
    log(run, 'SW.19 wpływ Enter', await enterSave(app, q, 'quick-time'))
    await page.waitForTimeout(800)
    log(run, 'SW.19 nowe', (await added(dataDir, before)).map(brief))

    // ---- SW.22 – pole „Kiedy”
    q = await openFresh(app, page)
    await typeAmount(q, '12,00')
    for (const v of ['dziś', 'wcz', 'przedwczoraj', '-3', '15', '29.10', '13.11', '31.02']) {
      const was = (await qread(q)).date
      await typeIn(q, 'quick-date', v)
      const r = await qread(q)
      log(run, `SW.22 data „${v}”`, was, '→', r.date, '| czas', r.time, '| przyszłość', (await q.getByTestId('quick-future').count()) ? await q.getByTestId('quick-future').innerText() : '-', '| komunikat w oknie', r.message, '| aria-invalid', await q.getByTestId('quick-date').getAttribute('aria-invalid'))
      if (v === '31.02') await snap(q, 'SW.22-31-02')
      if (v === '13.11') await snap(q, 'SW.22-13-11')
    }
    await typeIn(q, 'quick-date', 'dziś')
    for (const v of ['7:5', '25:00', '']) {
      const was = (await qread(q)).time
      await typeIn(q, 'quick-time', v)
      log(run, `SW.22 godzina „${v}”`, was, '→', (await qread(q)).time, '| okno', (await body(q)).slice(-160))
    }
    await snap(q, 'SW.22-godzina')
    before = await ops(dataDir)
    await category(q, CAT.groceries)
    log(run, 'SW.22 zapis bez godziny', await enterSave(app, q, 'quick-category'))
    await page.waitForTimeout(800)
    log(run, 'SW.22 nowe', (await added(dataDir, before)).map(brief))

    // ---- SW.23 – kwota: działania, format, brzegi
    q = await openFresh(app, page)
    await category(q, CAT.food)
    for (const v of ['12,50+8,30', '3*4,99', '10/3', '100-25,5', '1 234,56', '1234.5', '1.200', '0,005', 'abc', '999999,99', '0']) {
      const was = await q.getByTestId('quick-amount').inputValue()
      await typeAmount(q, v)
      const r = await qread(q)
      log(run, `SW.23 „${v}”`, was, '→', r.amount, '| podgląd', r.preview, '| komunikat', r.message)
      if (v === '1.200') await snap(q, 'SW.23-1-200')
    }
    log(run, 'SW.23 Enter przy 0', await enterSave(app, q))
    await snap(q, 'SW.23-zero')
    before = await ops(dataDir)
    await typeAmount(q, '3*4,99')
    log(run, 'SW.23 zapis 3*4,99', await enterSave(app, q))
    await page.waitForTimeout(800)
    log(run, 'SW.23 nowe', (await added(dataDir, before)).map(brief))

    // ---- SW.24 – kwota ujemna
    before = await ops(dataDir)
    q = await openFresh(app, page)
    await category(q, CAT.clothes)
    await typeAmount(q, '-49,99')
    log(run, 'SW.24 „-49,99”', await qread(q), '| okno', await body(q))
    await snap(q, 'SW.24-minus')
    await typeAmount(q, '20-69,99')
    log(run, 'SW.24 „20-69,99”', (await qread(q)).amount, (await qread(q)).preview)
    log(run, 'SW.24 Enter', await enterSave(app, q))
    await snap(q, 'SW.24-enter')
    log(run, 'SW.24 główne okno – komunikaty', (await page.getByRole('status').allInnerTexts().catch(() => [])).join(' | '))
    await q.keyboard.press('Escape')
    await waitHidden(app)
    log(run, 'SW.24 nowe', (await added(dataDir, before)).map(brief))

    // ---- SW.31 – Esc w polu, „×”, Enter w polu, Shift+Enter
    before = await ops(dataDir)
    q = await openFresh(app, page)
    await q.getByTestId('quick-amount').click()
    await q.getByTestId('quick-amount').fill('64,20')
    await q.getByTestId('quick-amount').press('Escape')
    log(run, 'SW.31 Esc w polu kwoty – okno ukryte', await waitHidden(app))
    q = await openQuick(app, page)
    log(run, 'SW.31 po ponownym otwarciu', (await qread(q)).amount, '| szkic', await q.getByTestId('quick-restored').count())
    if (await q.getByTestId('quick-clear').count()) await q.getByTestId('quick-clear').click()
    await q.getByTestId('quick-amount').click()
    await q.getByTestId('quick-amount').fill('64,20')
    await q.getByTestId('quick-close').click()
    log(run, 'SW.31 × – okno ukryte', await waitHidden(app))
    q = await openQuick(app, page)
    log(run, 'SW.31 po × ponowne otwarcie', (await qread(q)).amount, '| szkic', await q.getByTestId('quick-restored').count())
    if (await q.getByTestId('quick-clear').count()) await q.getByTestId('quick-clear').click()
    await category(q, CAT.groceries)
    await q.getByTestId('quick-amount').click()
    await q.getByTestId('quick-amount').fill('7,77')
    await q.getByTestId('quick-amount').press('Shift+Enter')
    await q.waitForTimeout(800)
    log(run, 'SW.31 Shift+Enter – okno widoczne', await quickVisible(app), '| kwota', await q.getByTestId('quick-amount').inputValue(), '| nowe', (await added(dataDir, before)).length)
    await q.getByTestId('quick-amount').click()
    await q.getByTestId('quick-amount').fill('8,88')
    log(run, 'SW.31 Enter w polu', await enterSave(app, q))
    await page.waitForTimeout(800)
    log(run, 'SW.31 nowe', (await added(dataDir, before)).map(brief))

    // ---- SW.32 – podwójny Enter, dwuklik „Zapisz”, otwarcie zaraz po „Zapisano.”
    before = await ops(dataDir)
    q = await openFresh(app, page)
    await category(q, CAT.groceries)
    await q.getByTestId('quick-amount').click()
    await q.getByTestId('quick-amount').fill('15,00')
    await q.getByTestId('quick-amount').press('Enter')
    await q.keyboard.press('Enter')
    await waitHidden(app)
    await page.waitForTimeout(1200)
    const n1 = await added(dataDir, before)
    log(run, 'SW.32 podwójny Enter – nowe', n1.length, n1.map(brief))
    before = await ops(dataDir)
    q = await openFresh(app, page)
    await category(q, CAT.groceries)
    await typeAmount(q, '15,00')
    await q.getByTestId('quick-save').dblclick()
    await waitHidden(app)
    await page.waitForTimeout(1200)
    const n2 = await added(dataDir, before)
    log(run, 'SW.32 dwuklik – nowe', n2.length)
    before = await ops(dataDir)
    q = await openFresh(app, page)
    await category(q, CAT.groceries)
    await typeAmount(q, '15,00')
    await q.getByTestId('quick-amount').press('Enter')
    await q.getByTestId('quick-message').waitFor({ timeout: 3000 })
    await page.evaluate('window.fi.quickOpen()')
    await q.waitForTimeout(2000)
    const r32 = await qread(q)
    log(run, 'SW.32 otwarte zaraz po „Zapisano.” – widoczne po 2 s', await quickVisible(app), '| formularz', r32)
    await snap(q, 'SW.32-ponownie')
    const n3 = await added(dataDir, before)
    log(run, 'SW.32 trzeci – nowe', n3.length)
    reading('sw', 'SW.32', 'rok', { podwojnyEnter: n1.length, dwuklik: n2.length, ponowneOtwarcie: n3.length })
    await q.keyboard.press('Escape')
  } finally {
    await app.close()
  }
})
