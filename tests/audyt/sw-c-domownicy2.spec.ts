    log(run, 'SW.14 procenty – nowe pliki', (await added(dataDir, before)).length)
    await q.locator('[aria-label="Jak podzielić"]').getByRole('radio', { name: 'kwoty' }).click()
    await q.waitForTimeout(200)
    log(run, 'SW.14 kwoty (po przełączeniu)', (await q.getByTestId('quick-joint').innerText()).replace(/\s+/g, ' '))
    const am = q.getByTestId('quick-joint-amount')
