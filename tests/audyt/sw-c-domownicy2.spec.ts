/**
 * SW.11, SW.12, SW.13, SW.14, SW.16, SW.28 – others' money in a member's transfer, a purchase a member finances (advance
 * first), a gift, a purchase paid jointly, a receipt with a member's line, „Powtórz ostatni”. Special state as sw-b.
 */
import { test, type Page } from '@playwright/test'
import { reading, text } from './lab'
import { CAT, SWM, addMembers, added, bridge, brief, category, enterSave, kind, log, openQuick, openRok, ops, qread, radarMembers, snap, typeAmount, typeIn } from './sw-pomoc'

const recv = (b: { receivables: string }) => b.receivables.replace('ROZLICZENIA Z DOMOWNIKAMI ', '').replace(/ Pożyczki udzielone.*/, '')
const shields = (b: { state: string }) => /Osłony · bufor na pensje ([^/]+)\//.exec(b.state)?.[1]?.trim() ?? '?'
const auto = (b: { envelopes: string }) => b.envelopes.replace('KOPERTY ? ', '').slice(0, 260)

async function inbox(page: Page): Promise<string> {
  await page.keyboard.press('Control+Shift+M')
  await page.waitForTimeout(1500)
  const t = (await text(page, 'main')).replace(/\s+/g, ' ')
  await page.keyboard.press('Control+1')
  return t.slice(0, 1500)
}

