    log(run, 'SW.28 wariant po kliknięciu', await qread(q), '| od domownika', await q.getByTestId('quick-payer').evaluate((s: HTMLSelectElement) => s.selectedOptions[0]?.textContent), '| przełącznik', await q.locator('[aria-label="Reszta wpłaty domownika"] [aria-checked="true"]').innerText().catch(() => '(brak)'))
