    const b4 = await bridge(page)
    q = await openQuick(app, page)
    await kind(q, 'Za domownika')
    await typeAmount(q, '200,00')
    await q.getByTestId('quick-financer').selectOption(SWM.babcia)
    log(run, 'SW.13 dymek prezent', await q.getByTestId('quick-gift').locator('xpath=..').getAttribute('title'))
