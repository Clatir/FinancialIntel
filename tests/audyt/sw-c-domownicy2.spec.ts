    log(run, 'SW.28 po kliknięciu', p28, '| finansuje', await q.getByTestId('quick-financer').evaluate((s: HTMLSelectElement) => s.selectedOptions[0]?.textContent), '| prezent', await q.getByTestId('quick-gift').isChecked())
    await snap(q, 'SW.28')
    log(run, 'SW.28 zapis', await enterSave(app, q, 'quick-amount'))
